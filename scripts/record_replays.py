"""Generate public playback from executions, never hand-authored state snapshots."""
import json
import tempfile
from pathlib import Path
from fleetlab.engine import Engine, LabError

ROOT = Path(__file__).resolve().parents[1]

class Clock:
    def __init__(self): self.now = 1792123200.0
    def __call__(self): return self.now
    def step(self, seconds=2): self.now += seconds

def record(kind):
    clock = Clock()
    with tempfile.TemporaryDirectory() as tmp:
        e = Engine(Path(tmp)/'state.sqlite3', clock=clock)
        e.seed()
        frames = []
        def frame(label, caption):
            s = e.snapshot('alpha')
            s['events'] = s['events'][-12:]
            # Keep the last suite per asset; records remain execution-derived.
            latest = {}
            for q in s['qualification']: latest[(q['asset_id'],q['test'])] = q
            s['qualification'] = list(latest.values())
            frames.append({'label':label,'caption':caption,'snapshot':s})
            clock.step()
        aid = 'alpha-gpu-01'
        frame('Discovered', 'Inventory exists; qualification has not yet established usable capacity.')
        if kind == 'burnin':
            e.commission('alpha',aid,'gpu_diagnostics')
            frame('Qualification failed', 'A simulated diagnostic fails. Allocation remains withheld; physical GPU burn-in is skipped.')
            e.commission('alpha',aid)
            frame('Policy passed', 'The synthetic fault is removed and the policy reruns. Passing simulation does not certify real hardware.')
            e.allocate('alpha',[aid]); frame('Allocated', 'Fresh qualified capacity is admitted to the simulated workload.')
        else:
            e.commission('alpha',aid); e.allocate('alpha',[aid])
            frame('Healthy workload', 'A qualified synthetic node runs a simulated workload at its reference step time.')
            if kind == 'telemetry':
                clock.step(45)
                e.observe('alpha',aid,fresh=False)
                frame('Visibility lost', 'Freshness expires. Health becomes unknown, with no invented hardware diagnosis.')
                e.observe('alpha',aid,healthy=True)
                frame('Visibility restored', 'A fresh simulated observation restores knowledge; no repair ticket was necessary.')
            else:
                e.inject('alpha',aid,'optic' if kind == 'worker-crash' else kind)
                e.observe('alpha',aid); frame('First symptom', 'One observation changes workload progress, but does not authorize disruptive repair.')
                for _ in range(2): clock.step(); e.observe('alpha',aid)
                frame('Persistent evidence', 'Three observations open one incident. The correlation is deterministic lab policy, not a causal proof.')
                iid = e.snapshot('alpha')['incidents'][0]['id']
                if kind == 'worker-crash':
                    try: e.advance('alpha',iid,fail_after_commit=True)
                    except RuntimeError: pass
                    e = Engine(Path(tmp)/'state.sqlite3',clock=clock)
                    frame('Worker reopened', 'A crash after commit leaves the durable next stage intact. Reopening the database does not repeat the effect.')
                while True:
                    inc = e.snapshot('alpha')['incidents'][0]
                    if inc['status'] == 'resolved': break
                    if inc['stage'] == 'wait_repair':
                        ticket = e.snapshot('alpha')['tickets'][0]
                        e.complete_ticket('alpha',ticket['id'])
                        frame('Technician completion', 'The simulated technician reports completion. Capacity remains withheld until validation.')
                    e.advance('alpha',iid,expected_version=inc['version'])
                    nxt = e.snapshot('alpha')['incidents'][0]
                    frame(nxt['stage'].replace('_',' ').title(), 'The transactional workflow records one bounded transition and its evidence.')
                w = e.snapshot('alpha')['workloads'][0]
                e.release('alpha',w['id']); frame('Idle baseline rechecked', 'Workload release reruns qualification before idle capacity is advertised again.')
        return {'id':kind,'title':kind.replace('-',' ').title(),'description':'Executed synthetic scenario with durable state and explicit provenance.','frames':frames}

def main():
    scenarios = [record(k) for k in ('optic','burnin','thermal','telemetry','worker-crash','storage')]
    evidence = {'schema_version':1,'provenance':'Generated by scripts/record_replays.py using the real state engine and a deterministic lab clock. Hardware and workload signals are synthetic. IDs are generated, not production identifiers.','scenarios':scenarios,'verification':{}}
    target = ROOT/'web/evidence.json'
    target.write_text(json.dumps(evidence,separators=(',',':'))+'\n')
    print(json.dumps({'scenarios':len(scenarios),'frames':sum(len(s['frames']) for s in scenarios),'bytes':target.stat().st_size}))

if __name__ == '__main__': main()
